<?php
// Builds src/www/js/core/pages.js: which page files (js/pages/*.js) the interface loads for a view. The core scripts
// (js/core/*.js, app.js) come with the page; a page file comes when its view is opened, with every page file it
// mentions (a page calls into another one: the pick results share a strategy via the community page).
//
// A mention is any whole-word match of a top-level name, comments and strings included: a file too many costs a
// request, a file too few would break a button. Core files may name a page's view only in quotes ('viewDns' — the
// router loads it by name); naming any other page function in core is an error: move that function to core.
//
// php scripts/pagemap.php [src/www]        — writes js/core/pages.js
// php scripts/pagemap.php [src/www] check  — exits 1 if js/core/pages.js is not up to date
$www = rtrim($argv[1] ?? __DIR__ . '/../src/www', '/\\');
$check = ($argv[2] ?? '') === 'check';
$read = fn(string $f) => file_get_contents("$www/$f");
$pages = array_map(fn($f) => basename($f, '.js'), glob("$www/js/pages/*.js"));
sort($pages);
$core = array_merge(array_map(fn($f) => 'js/core/' . basename($f), glob("$www/js/core/*.js")), ['app.js']);
$core = array_values(array_filter($core, fn($f) => $f !== 'js/core/pages.js'));

// top-level names of a file: function, async function, const, let, var, class at column 0
$namesOf = function (string $src): array {
  preg_match_all('/^(?:async\s+)?function\s*\*?\s*([A-Za-z_$][\w$]*)|^(?:const|let|var|class)\s+([A-Za-z_$][\w$]*)/m', $src, $m);
  return array_values(array_filter(array_map(fn($a, $b) => $a !== '' ? $a : $b, $m[1], $m[2])));
};
$mentions = fn(string $src, string $name) => (bool)preg_match('/(?<![\w$.])' . preg_quote($name, '/') . '(?![\w$])/', $src);

$owner = [];   // name => page
$err = [];
foreach ($pages as $p) {
  foreach ($namesOf($read("js/pages/$p.js")) as $n) {
    if (isset($owner[$n])) $err[] = "$n is declared in pages/{$owner[$n]}.js and pages/$p.js";
    $owner[$n] = $p;
  }
}
$coreNames = [];
foreach ($core as $f) foreach ($namesOf($read($f)) as $n) $coreNames[$n] = $f;
foreach ($owner as $n => $p) if (isset($coreNames[$n])) $err[] = "$n is declared in {$coreNames[$n]} and pages/$p.js";

// page → pages it mentions
$edges = [];
foreach ($pages as $p) {
  $src = $read("js/pages/$p.js");
  $edges[$p] = [];
  foreach ($owner as $n => $q) if ($q !== $p && $mentions($src, $n)) $edges[$p][$q] = true;
}
// views the core names in quotes, and page names it must not call directly
$views = [];
foreach ($core as $f) {
  $src = $read($f);
  preg_match_all("/'([A-Za-z_$][\w$]*)'/", $src, $q);
  foreach ($q[1] as $n) if (isset($owner[$n])) $views[$n] = true;
  $bare = preg_replace("/'[A-Za-z_$][\w$]*'/", "''", $src);
  foreach ($owner as $n => $p) if ($mentions($bare, $n)) $err[] = "$f calls $n from pages/$p.js: move it to core or name the view in quotes";
}
if ($err) {
  fwrite(STDERR, implode("\n", array_unique($err)) . "\n");
  exit(2);
}
ksort($views);
$need = [];
foreach (array_keys($views) as $v) {
  $seen = [];
  $stack = [$owner[$v]];
  while ($stack) {
    $p = array_pop($stack);
    if (isset($seen[$p])) continue;
    $seen[$p] = true;
    foreach ($edges[$p] as $q => $_) $stack[] = $q;
  }
  $files = array_keys($seen);
  sort($files);
  $need[$v] = $files;
}
$lines = [];
foreach ($need as $v => $files) $lines[] = "  $v: [" . implode(', ', array_map(fn($f) => "'$f'", $files)) . '],';
$js = "'use strict';\n// Generated by scripts/pagemap.php — do not edit. A view the router opens by name → the page files (js/pages) it\n"
  . "// needs; core scripts are already loaded.\n\nconst PAGE_NEEDS = {\n" . implode("\n", $lines) . "\n};\n";
$file = "$www/js/core/pages.js";
if ($check) {
  if (!is_file($file) || file_get_contents($file) !== $js) {
    fwrite(STDERR, "js/core/pages.js is out of date: run php scripts/pagemap.php\n");
    exit(1);
  }
  exit(0);
}
file_put_contents($file, $js);
$size = fn(array $fs) => array_sum(array_map(fn($f) => filesize("$www/js/pages/$f.js"), $fs)) >> 10;
foreach ($need as $v => $files) printf("%-14s %3d KB  %s\n", $v, $size($files), implode(',', $files));
$cs = array_sum(array_map(fn($f) => filesize("$www/$f"), $core)) >> 10;
printf("core: %d KB, all pages: %d KB\n", $cs, $size($pages));
